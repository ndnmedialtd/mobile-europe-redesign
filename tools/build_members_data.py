"""Build me-redesign/members-data.js: real stories per topic, used for the Members area recommendations.

Run from the repo root:  python3 tools/build_members_data.py
"""
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / "tools" / "category_data.json").read_text())
NAMES = {
    "access": "Access", "automation-ai": "Automation/AI", "bss-oss-cx": "BSS/OSS/CX", "cloud-nfv": "Cloud/NFV",
    "digital-platforms-apis": "Digital Platforms & APIs", "edge": "Edge", "financial-regulation": "Financial/Regulation",
    "optical-ip": "Optical/IP", "ran": "RAN", "satellite": "Satellite", "security": "Security", "sustainability": "Sustainability",
}
stories = {}
for slug, items in data.items():
    stories[NAMES[slug]] = [
        {"t": t, "img": img, "date": d}
        for t, img, tag, d, ex in items if not t.lower().startswith("download:")
    ]
# 5G & Beyond is hand-made in the mockup, so its stories are listed here
stories["5G & Beyond"] = [
    {"t": "VodafoneThree, Nokia partner to trial AI-powered mobile networks", "img": "2026/11/Nokia-VodafoneThree.png", "date": "18 November 2026"},
    {"t": "Belgium confirms 2G shutdown plans for 2028/29", "img": "2026/11/Belgium.png", "date": "17 November 2026"},
    {"t": "Nokia, Nscale and Telia partner to build Nordic AI Gigafactory", "img": "2026/11/Nokia-Telia.png", "date": "16 November 2026"},
    {"t": "SpaceX taps Qualcomm for nationwide Starlink Mobile 5G rollout", "img": "2024/09/Starlink-AdobeStock_955157965_Editorial_Use_Only-Sept-2024-696x464.jpg", "date": "5 November 2026"},
    {"t": "VodafoneThree deploys Ericsson’s latest 5G radio technology in London", "img": "2025/06/VodafoneThree-Merger-Logo-June-25-696x464.jpg", "date": "5 November 2026"},
    {"t": "Ericsson, Telia sign 6G partnership agreement", "img": "2026/11/Telia-Ericsson.png", "date": "3 November 2026"},
]
out = ROOT / os.environ.get("ME_OUT", "me-redesign") / "members-data.js"
out.write_text("// Generated by tools/build_members_data.py: real stories per topic for Members-area recommendations\n"
               "window.ME_STORIES = " + json.dumps(stories, ensure_ascii=False, indent=1) + ";\n")
print("wrote", out.name, {k: len(v) for k, v in stories.items()})
